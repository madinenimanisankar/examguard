import { useCallback, useEffect, useState } from "react";
import { toast } from "sonner";
import http, { apiError } from "@/utils/api";
import { RiskBadge, StatusPill } from "@/components/bits";
import { Button } from "@/components/ui/button";
import { Label } from "@/components/ui/label";
import { Radar, ShieldAlert, RefreshCw } from "lucide-react";

const REVIEW_STATES = ["new", "under_review", "resolved", "inconclusive"];

export default function AlertsConsole() {
  const [alerts, setAlerts] = useState([]);
  const [exams, setExams] = useState([]);
  const [examFilter, setExamFilter] = useState("");
  const [statusFilter, setStatusFilter] = useState("");
  const [selected, setSelected] = useState(null);

  const load = useCallback(() => {
    const params = new URLSearchParams();
    if (examFilter) params.set("examId", examFilter);
    if (statusFilter) params.set("status", statusFilter);
    http.get(`/security/alerts?${params.toString()}`).then(({ data }) => setAlerts(data.alerts)).catch((e) => toast.error(apiError(e)));
  }, [examFilter, statusFilter]);

  useEffect(() => {
    http.get("/exams").then(({ data }) => setExams(data.exams)).catch(() => {});
  }, []);
  useEffect(load, [load]);

  const review = async (alertId, status) => {
    try {
      await http.post(`/security/alerts/${alertId}/review`, { status, note: status === "under_review" ? "Review started" : undefined });
      toast.success(`Alert marked ${status.replace("_", " ")}`);
      load();
      if (selected) setSelected(null);
    } catch (e) {
      toast.error(apiError(e));
    }
  };

  return (
    <div className="console-scope console-grid-bg -mx-4 -my-8 min-h-[calc(100vh-4rem)] bg-background px-4 py-8 sm:-mx-6 sm:px-6" data-testid="alerts-console">
      <div className="mx-auto max-w-7xl">
        <div className="mb-8 flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
          <div>
            <h1 className="flex items-center gap-3 font-display text-2xl font-bold tracking-tight text-foreground sm:text-3xl" data-testid="alerts-title">
              <Radar className="h-7 w-7 text-primary" /> Security alerts console
            </h1>
            <p className="mt-1 max-w-2xl text-sm text-muted-foreground">
              Technical detections generated by the rule engine — each alert lists its reasons. A detection is <span className="font-semibold text-foreground">not a finding of misconduct</span>; reviewers decide.
            </p>
          </div>
          <Button variant="outline" size="sm" onClick={load} data-testid="alerts-refresh-button" className="gap-2"><RefreshCw className="h-4 w-4" /> Refresh</Button>
        </div>

        <div className="mb-6 flex flex-wrap gap-3">
          <select data-testid="alert-exam-filter" className="rounded-lg border bg-card px-3 py-2 text-sm" value={examFilter} onChange={(e) => setExamFilter(e.target.value)}>
            <option value="">All examinations</option>
            {exams.map((x) => <option key={x._id} value={x._id}>{x.title}</option>)}
          </select>
          <select data-testid="alert-status-filter" className="rounded-lg border bg-card px-3 py-2 text-sm" value={statusFilter} onChange={(e) => setStatusFilter(e.target.value)}>
            <option value="">All statuses</option>
            {REVIEW_STATES.map((s) => <option key={s} value={s}>{s.replace("_", " ")}</option>)}
          </select>
        </div>

        {alerts.length === 0 ? (
          <div className="flex flex-col items-center justify-center gap-3 rounded-xl border border-dashed py-16 text-center" data-testid="no-alerts">
            <ShieldAlert className="h-10 w-10 text-muted-foreground/50" />
            <p className="font-display font-semibold text-foreground">No alerts match this filter</p>
            <p className="max-w-sm text-sm text-muted-foreground">Alerts appear when the rule engine's thresholds are crossed. Use the demo simulator on an exam's Monitor page to try the workflow.</p>
          </div>
        ) : (
          <div className="grid gap-4 lg:grid-cols-5">
            <div className="space-y-3 lg:col-span-3">
              {alerts.map((a) => (
                <button
                  key={a._id}
                  data-testid={`alert-card-${a._id}`}
                  onClick={() => setSelected(a)}
                  className={`w-full rounded-xl border bg-card p-4 text-left transition-colors hover:border-primary/50 ${selected?._id === a._id ? "border-primary/60" : ""}`}
                >
                  <div className="flex flex-wrap items-center gap-2">
                    <RiskBadge level={a.riskLevel} score={a.riskScore} />
                    <StatusPill status={a.status} />
                    <span className="rounded-full border border-red-500/30 bg-red-500/10 px-2 py-0.5 text-[10px] font-bold uppercase tracking-wider text-red-300" data-testid="alert-source-tag">
                      {a.evidence?.some((e) => e.source === "simulation") ? "simulated demo" : "browser signal"}
                    </span>
                  </div>
                  <p className="mt-2 text-sm font-semibold text-foreground" data-testid="alert-candidate">{a.candidateId?.email || "candidate"} — {a.examId?.title}</p>
                  <p className="mt-0.5 text-xs text-muted-foreground">{new Date(a.createdAt).toLocaleString()} · category: {a.category.replace(/_/g, " ")}</p>
                </button>
              ))}
            </div>

            <div className="lg:col-span-2">
              {selected ? (
                <div className="rounded-xl border bg-card p-5" data-testid="alert-detail">
                  <h2 className="font-display font-semibold text-foreground" data-testid="alert-detail-title">Why this alert fired</h2>
                  <ul className="mt-3 space-y-2" data-testid="alert-reasons">
                    {selected.reasons?.map((r, i) => (
                      <li key={i} className="flex items-start gap-2 rounded-lg bg-muted/60 p-2.5 text-xs text-foreground"><span className="font-bold text-primary">+</span>{r}</li>
                    ))}
                  </ul>
                  <h3 className="mt-5 text-xs font-bold uppercase tracking-wider text-muted-foreground">Evidence</h3>
                  <div className="mt-2 space-y-1.5" data-testid="alert-evidence">
                    {selected.evidence?.map((e, i) => (
                      <div key={i} className="flex items-center justify-between rounded border px-2.5 py-1.5 text-xs text-foreground">
                        <span>{e.type.replace(/_/g, " ")}{e.meta?.processName ? ` — ${e.meta.processName}` : ""}</span>
                        <span className="text-muted-foreground">{new Date(e.at).toLocaleTimeString()}</span>
                      </div>
                    ))}
                  </div>
                  {selected.review?.notes?.length > 0 && (
                    <>
                      <h3 className="mt-5 text-xs font-bold uppercase tracking-wider text-muted-foreground">Reviewer notes</h3>
                      <div className="mt-2 space-y-1.5">
                        {selected.review.notes.map((n, i) => (
                          <p key={i} className="rounded bg-muted/60 p-2 text-xs text-foreground" data-testid="alert-note">{n.text} — {n.by}</p>
                        ))}
                      </div>
                    </>
                  )}
                  <h3 className="mt-5 text-xs font-bold uppercase tracking-wider text-muted-foreground">Review decision</h3>
                  <div className="mt-2 grid grid-cols-2 gap-2" data-testid="review-actions">
                    {REVIEW_STATES.filter((s) => s !== "new").map((s) => (
                      <Button key={s} variant="outline" size="sm" data-testid={`review-${s}-button`} onClick={() => review(selected._id, s)}>
                        {s.replace("_", " ")}
                      </Button>
                    ))}
                  </div>
                </div>
              ) : (
                <div className="flex h-full items-center justify-center rounded-xl border border-dashed p-8 text-center text-sm text-muted-foreground" data-testid="alert-detail-placeholder">
                  Select an alert to see its explainable reasons, evidence and review actions.
                </div>
              )}
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
