import { useCallback, useEffect, useState } from "react";
import { toast } from "sonner";
import http, { apiError } from "@/utils/api";
import { RiskBadge, StatusPill } from "@/components/bits";
import { Button } from "@/components/ui/button";
import { Radar, ShieldAlert, RefreshCw } from "lucide-react";

const REVIEW_STATES = ["new", "under_review", "resolved", "inconclusive"];

export default function AlertsConsole() {
  const [alerts, setAlerts] = useState([]);
  const [exams, setExams] = useState([]);
  const [examFilter, setExamFilter] = useState("");
  const [statusFilter, setStatusFilter] = useState("");
  const [selected, setSelected] = useState(null);

  const load = useCallback(() => {
    const params = new URLSearchParams();
    if (examFilter) params.set("examId", examFilter);
    if (statusFilter) params.set("status", statusFilter);
    http
      .get(`/security/alerts?${params.toString()}`)
      .then(({ data }) => setAlerts(data.alerts))
      .catch((e) => toast.error(apiError(e)));
  }, [examFilter, statusFilter]);

  useEffect(() => {
    http.get("/exams").then(({ data }) => setExams(data.exams)).catch(() => {});
  }, []);

  useEffect(load, [load]);

  const review = async (alertId, status) => {
    try {
      await http.post(`/security/alerts/${alertId}/review`, {
        status,
        note: status === "under_review" ? "Review started" : undefined,
      });
      toast.success(`Alert marked ${status.replace("_", " ")}`);
      load();
      if (selected) setSelected(null);
    } catch (e) {
      toast.error(apiError(e));
    }
  };

  return (
    <div className="mx-auto max-w-7xl py-2" data-testid="alerts-console">
      {/* Header matching "My examinations" */}
      <div className="mb-8 flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h1
            className="flex items-center gap-2.5 font-display text-2xl font-bold tracking-tight text-slate-900 sm:text-3xl"
            data-testid="alerts-title"
          >
            <Radar className="h-7 w-7 text-blue-600" /> Security alerts console
          </h1>
          <p className="mt-1.5 max-w-2xl text-sm text-slate-500">
            Technical detections generated by the rule engine — each alert lists its reasons. A detection is{" "}
            <span className="font-semibold text-slate-800">not a finding of misconduct</span>; reviewers decide.
          </p>
        </div>

        <Button
          size="sm"
          onClick={load}
          data-testid="alerts-refresh-button"
          className="gap-2 rounded-lg bg-blue-600 px-4 py-2 text-sm font-medium text-white shadow-sm hover:bg-blue-700"
        >
          <RefreshCw className="h-4 w-4" /> Refresh
        </Button>
      </div>

      {/* Filters */}
      <div className="mb-6 flex flex-wrap gap-3">
        <select
          data-testid="alert-exam-filter"
          className="rounded-lg border border-slate-200 bg-white px-3.5 py-2 text-sm font-medium text-slate-700 shadow-2xs transition-colors hover:border-slate-300 focus:border-blue-600 focus:outline-none"
          value={examFilter}
          onChange={(e) => setExamFilter(e.target.value)}
        >
          <option value="">All examinations</option>
          {exams.map((x) => (
            <option key={x._id} value={x._id}>
              {x.title}
            </option>
          ))}
        </select>

        <select
          data-testid="alert-status-filter"
          className="rounded-lg border border-slate-200 bg-white px-3.5 py-2 text-sm font-medium text-slate-700 shadow-2xs transition-colors hover:border-slate-300 focus:border-blue-600 focus:outline-none"
          value={statusFilter}
          onChange={(e) => setStatusFilter(e.target.value)}
        >
          <option value="">All statuses</option>
          {REVIEW_STATES.map((s) => (
            <option key={s} value={s}>
              {s.replace("_", " ")}
            </option>
          ))}
        </select>
      </div>

      {/* Empty state or Alert List + Detail Panel */}
      {alerts.length === 0 ? (
        <div
          className="flex flex-col items-center justify-center gap-3 rounded-xl border border-slate-200 bg-white py-16 text-center shadow-2xs"
          data-testid="no-alerts"
        >
          <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-slate-100 text-slate-500">
            <ShieldAlert className="h-6 w-6" />
          </div>
          <p className="font-display text-base font-bold text-slate-900">No alerts match this filter</p>
          <p className="max-w-md text-sm text-slate-500">
            Alerts appear when the rule engine's thresholds are crossed. Use the demo simulator on an exam's Monitor
            page to try the workflow.
          </p>
        </div>
      ) : (
        <div className="grid gap-5 lg:grid-cols-5">
          {/* Left column: Alert cards */}
          <div className="space-y-3 lg:col-span-3">
            {alerts.map((a) => (
              <button
                key={a._id}
                data-testid={`alert-card-${a._id}`}
                onClick={() => setSelected(a)}
                className={`w-full rounded-xl border bg-white p-5 text-left transition-all hover:border-slate-300 hover:shadow-sm ${
                  selected?._id === a._id
                    ? "border-blue-600 ring-2 ring-blue-600/15"
                    : "border-slate-200"
                }`}
              >
                <div className="flex flex-wrap items-center gap-2">
                  <RiskBadge level={a.riskLevel} score={a.riskScore} />
                  <StatusPill status={a.status} />
                  <span
                    className="rounded-full border border-emerald-200 bg-emerald-50 px-2.5 py-0.5 text-[11px] font-semibold tracking-wide text-emerald-700"
                    data-testid="alert-source-tag"
                  >
                    {a.evidence?.some((e) => e.source === "simulation") ? "Simulated demo" : "Browser signal"}
                  </span>
                </div>
                <p className="mt-3 text-base font-bold text-slate-900" data-testid="alert-candidate">
                  {a.candidateId?.email || "candidate"} — {a.examId?.title}
                </p>
                <p className="mt-1 text-xs text-slate-500">
                  {new Date(a.createdAt).toLocaleString()} · category: {a.category.replace(/_/g, " ")}
                </p>
              </button>
            ))}
          </div>

          {/* Right column: Selected alert details */}
          <div className="lg:col-span-2">
            {selected ? (
              <div
                className="rounded-xl border border-slate-200 bg-white p-6 shadow-2xs"
                data-testid="alert-detail"
              >
                <h2
                  className="font-display text-base font-bold text-slate-900"
                  data-testid="alert-detail-title"
                >
                  Why this alert fired
                </h2>
                <ul className="mt-3 space-y-2" data-testid="alert-reasons">
                  {selected.reasons?.map((r, i) => (
                    <li
                      key={i}
                      className="flex items-start gap-2 rounded-lg bg-slate-100/80 p-3 text-xs font-medium text-slate-700"
                    >
                      <span className="font-bold text-blue-600">+</span>
                      <span>{r}</span>
                    </li>
                  ))}
                </ul>

                <h3 className="mt-6 text-xs font-bold uppercase tracking-wider text-slate-400">
                  Evidence
                </h3>
                <div className="mt-2 space-y-1.5" data-testid="alert-evidence">
                  {selected.evidence?.map((e, i) => (
                    <div
                      key={i}
                      className="flex items-center justify-between rounded-lg border border-slate-200 bg-slate-50/60 px-3 py-2 text-xs text-slate-700"
                    >
                      <span className="font-medium">
                        {e.type.replace(/_/g, " ")}
                        {e.meta?.processName ? ` — ${e.meta.processName}` : ""}
                      </span>
                      <span className="text-slate-400">{new Date(e.at).toLocaleTimeString()}</span>
                    </div>
                  ))}
                </div>

                {selected.review?.notes?.length > 0 && (
                  <>
                    <h3 className="mt-6 text-xs font-bold uppercase tracking-wider text-slate-400">
                      Reviewer notes
                    </h3>
                    <div className="mt-2 space-y-1.5">
                      {selected.review.notes.map((n, i) => (
                        <p
                          key={i}
                          className="rounded-lg bg-slate-100/80 p-2.5 text-xs text-slate-700"
                          data-testid="alert-note"
                        >
                          {n.text} — <span className="font-medium text-slate-900">{n.by}</span>
                        </p>
                      ))}
                    </div>
                  </>
                )}

                <h3 className="mt-6 text-xs font-bold uppercase tracking-wider text-slate-400">
                  Review decision
                </h3>
                <div className="mt-2.5 grid grid-cols-2 gap-2" data-testid="review-actions">
                  {REVIEW_STATES.filter((s) => s !== "new").map((s) => (
                    <Button
                      key={s}
                      variant="outline"
                      size="sm"
                      className="rounded-lg border-slate-200 bg-white text-xs font-medium capitalize text-slate-700 hover:bg-slate-50 hover:text-slate-900"
                      data-testid={`review-${s}-button`}
                      onClick={() => review(selected._id, s)}
                    >
                      {s.replace("_", " ")}
                    </Button>
                  ))}
                </div>
              </div>
            ) : (
              <div
                className="flex h-full min-h-[260px] items-center justify-center rounded-xl border border-slate-200 bg-white p-8 text-center text-sm text-slate-500"
                data-testid="alert-detail-placeholder"
              >
                Select an alert to see its explainable reasons, evidence and review actions.
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
}